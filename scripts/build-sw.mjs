// Writes dist/sw.js: precaches every built file (except social images) so the
// whole site — generator, scanner, batch, print — works offline after one visit.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = fileURLToPath(new URL('../dist', import.meta.url));
const base = (process.env.PUBLIC_BASE_PATH || '/').replace(/\/?$/, '/');
const SKIP = [
  /^og\//,
  /^sw\.js$/,
  /^_headers$/,
  /^_redirects$/,
  /^robots\.txt$/,
  /^sitemap.*\.xml$/,
  /\.map$/,
];

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const hash = createHash('sha256');
const urls = [];
for (const file of walk(dist).sort()) {
  const rel = relative(dist, file).split(sep).join('/');
  if (SKIP.some((re) => re.test(rel))) continue;
  hash.update(rel).update(readFileSync(file));
  // Pages are requested by clean URL (/wifi-qr-code-generator), so cache them under that.
  const url =
    rel === 'index.html' ? base : rel.endsWith('.html') ? base + rel.slice(0, -5) : base + rel;
  urls.push([url, base + rel]);
}
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/build-sw.mjs — do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = 'pakkaqr-' + VERSION;
const FILES = ${JSON.stringify(urls)};
const HOME = ${JSON.stringify(base)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) =>
      Promise.all(
        FILES.map(([key, file]) =>
          fetch(file, { cache: 'no-cache' }).then((res) => (res.ok ? cache.put(key, res) : undefined)),
        ),
      ),
    ).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('pakkaqr-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

const cleanPath = (url) => url.pathname.replace(/\\.html$/, '').replace(/(.)\\/$/, '$1');

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // Network first for pages (fresh content), cache when offline.
    event.respondWith(
      fetch(req).catch(() =>
        caches.open(CACHE).then((cache) =>
          cache.match(cleanPath(url)).then((hit) => hit || cache.match(HOME)),
        ),
      ),
    );
    return;
  }
  // Hashed assets never change: cache first.
  event.respondWith(caches.match(url.pathname).then((hit) => hit || fetch(req)));
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`[sw] precache ${urls.length} files, version ${version}`);
